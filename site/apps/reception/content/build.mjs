// Mechanical, lossless split of authored content. Original source modules stay intact.
import {mkdir, writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import * as source from '../js/cases.js';
import * as evidence from '../js/evidence-catalog.js';
import {SOURCE_INDEX} from '../js/source-index.js';
const output = new URL('./', import.meta.url);
const json = value => JSON.stringify(value);
const hash = value => createHash('sha256').update(json(value)).digest('hex');
const write = async (path, value) => writeFile(new URL(path, output), json(value) + '\n');
await mkdir(new URL('cases/', output), {recursive: true});
const metadata = source.CASE_TEMPLATES.map(c => ({
  id:c.id,familyId:c.familyId,curriculumId:c.curriculumId,title:c.title,topic:c.topic,
  level:c.level,difficulty:c.difficulty,evidenceTaskId:c.evidenceTaskId,
  estimatedMinutes:c.estimatedMinutes,datePacks:c.datePacks,
  calendar:{anchor:c.calendar.anchor,events:c.calendar.events.map(e=>({id:e.id,date:e.date})),duration:c.calendar.duration,unit:c.calendar.unit,startPolicy:c.calendar.startPolicy,lastDayPolicy:c.calendar.lastDayPolicy}
}));
const common = {sources:source.SOURCES,metadata:SOURCE_INDEX.entries.filter(e=>e.collection==='shelf')};
const resources = {};
for (const template of source.CASE_TEMPLATES) {
  const task = evidence.EVIDENCE_TASKS[template.evidenceTaskId];
  if (!task) throw Error(`Missing evidence task: ${template.id}`);
  const recordIds = new Set(task.recordIds);
  const pack = {template,task,records:evidence.EVIDENCE_RECORDS.filter(r=>recordIds.has(r.id)),metadata:SOURCE_INDEX.entries.filter(e=>e.collection!=='shelf'&&recordIds.has(e.recordId))};
  resources[template.id] = {path:`cases/${template.id}.json`,sha256:hash(pack)};
  await write(resources[template.id].path,pack);
}
const catalog = source.CASE_TEMPLATES.map(c=>({id:c.id,title:c.title,topic:c.topic,opening:c.opening,role:{title:c.role.title}}));
await write('common.json',common);
await write('catalog.json',catalog);
await write('source-index.json',SOURCE_INDEX);
const {entries,...indexHeader} = SOURCE_INDEX;
const manifest = {schema:1,contentVersion:source.CONTENT_VERSION,version:source.VERSION,rubricVersion:source.RUBRIC_VERSION,legalDate:source.LEGAL_DATE,evidenceVersion:evidence.EVIDENCE_VERSION,evidenceDate:evidence.EVIDENCE_DATE,role:source.ROLE,rubric:source.RUBRIC,bank:source.BANK_INFO,indexHeader,sourceOrder:entries.map(e=>e.id),recordOrder:evidence.EVIDENCE_RECORDS.map(r=>r.id),templates:metadata,resources,commonSHA256:hash(common),catalogSHA256:hash(catalog),indexSHA256:hash(SOURCE_INDEX)};
await writeFile(new URL('manifest.js', output),`// Generated by content/build.mjs. Assignment/calendar metadata only; full case bodies load separately.\nexport const CONTENT_MANIFEST=${json(manifest)};\n`);
console.log(JSON.stringify({templates:metadata.length,manifestBytes:Buffer.byteLength(json(manifest)),commonBytes:Buffer.byteLength(json(common)),catalogBytes:Buffer.byteLength(json(catalog)),originalBytes:Buffer.byteLength(json(source.CASE_TEMPLATES))}));

