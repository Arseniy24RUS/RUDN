  await mkdir(new URL('fixtures/',output),{recursive:true});
  const args={period:'2026-2027',calendarYear:2026,calendarSnapshot:BUNDLED_CALENDARS,seed:'reception-legacy-compatibility',id:'reception-legacy-synthetic'};
  const state=newShift('student:9909133001','assessment',args),c=caseById(state.caseIds[0],state),p=state.cases[c.id];
  p.asked=[c.questions[0].id];p.lastQuestion=c.questions[0].id;p.knowledge.url='https://example.test/student-original';p.evidence.query='Мой исходный запрос';state.screen='work';state.revision=7;
