export function translator(locale) {
  const dictionary = COPY[normalizeLocale(locale)];
  return (key, vars = {}) => String(dictionary[key] ?? COPY.ru[key] ?? key)
    .replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? ''));
}
