#!/usr/bin/env node
/** Extract the authored post-training contrasts; never ship this registry to site/. */
import {readFile,readdir,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {CONTENT_MANIFEST} from '../site/apps/reception/content/manifest.js';
const base=new URL('../site/apps/reception/',import.meta.url);
const destination=new URL('../firebase/functions/reception-ai/learning-review-data.mjs',import.meta.url);
const json=async url=>JSON.parse(await readFile(url,'utf8'));
const locales={},catalogs={},common={};
for(const locale of ['en','zh']){
  locales[locale]=await json(new URL(`localization/compiled/${locale}.manifest.json`,base));
  catalogs[locale]=await json(new URL('localization/compiled/'+locales[locale].entries.catalog.path,base));
  common[locale]=await json(new URL('localization/compiled/'+locales[locale].entries.common.path,base));
}
const records={};
for(const filename of (await readdir(new URL('content/cases/',base))).filter(name=>name.endsWith('.json')).sort()){
  const raw=await readFile(new URL('content/cases/'+filename,base),'utf8'),row=JSON.parse(raw).template;
  const packs={};
  for(const locale of ['en','zh']){
    const entry=locales[locale].entries['cases/'+row.id];
    if(!entry)throw Error(`Missing ${locale} case pack: ${row.id}`);
    packs[locale]=await json(new URL('localization/compiled/'+entry.path,base));
  }
  const localized=value=>{
    if(!value)return undefined;
    const result={ru:value};
    for(const locale of ['en','zh']){
      const translated=packs[locale].strings[value]||catalogs[locale].strings[value]||common[locale].strings[value];
      if(typeof translated!=='string'||!translated.trim())throw Error(`Missing ${locale} learning review text: ${row.id}`);
      result[locale]=translated;
    }
    return result;
  };
  records[row.id]={
    sourceContentVersion:row.contentVersion,sourceSHA256:createHash('sha256').update(raw).digest('hex'),
    curriculumId:row.curriculumId||null,title:localized(row.title),
    ...(row.contrast?{contrast:{difference:localized(row.contrast.difference),...(row.contrast.decision?{decision:localized(row.contrast.decision)}:{})}}:{}),
  };
}
const output='// Generated by scripts/reception-ai-learning-review.mjs. Server-only authored feedback.\n'
  +`export const LEARNING_REVIEW_CONTENT_VERSION=${JSON.stringify(CONTENT_MANIFEST.contentVersion)};\n`
  +`export const LEARNING_REVIEW_DATA=Object.freeze(${JSON.stringify(records,null,2)});\n`;
if(process.argv.includes('--check')){
  if(await readFile(destination,'utf8')!==output)throw Error('Learning review registry is stale; run node scripts/reception-ai-learning-review.mjs');
}else await writeFile(destination,output);
console.log(JSON.stringify({cases:Object.keys(records).length,authoredContrasts:Object.values(records).filter(row=>row.contrast).length,authoredConclusions:Object.values(records).filter(row=>row.contrast?.decision).length,locales:['ru','en','zh'],checked:process.argv.includes('--check')}));
