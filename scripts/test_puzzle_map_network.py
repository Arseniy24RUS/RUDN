import traceback
from urllib.parse import urlsplit

from playwright.async_api import async_playwright
from test_puzzle_catalog import (
    PuzzleServer, ROOT, STUDENT, check_layout, initializer, place_pieces, ready,
    trusted_drop,
)

SITE = ROOT / 'site'
GEOMETRY_PATH = '/RUDN/assets/puzzle/data/russia_subjects_89.topojson'
COMPACT_PATH = '/RUDN/assets/puzzle/data/russia_subjects_89.compact.json'
OWNER = 'student:' + STUDENT['studentKey']
SCOPE = {'owner': OWNER, 'activitySlug': 'seminar-2', 'mode': 'seminar'}


def pending_geometry_storage(kind):
    """Stall only the optional map cache; keep student progress storage real."""
    return """(()=>{
      const kind=%s, name='rudn-puzzle-geometry-v1';
      window.__qaGeometryFaultHits=[];
      const hit=stage=>window.__qaGeometryFaultHits.push(stage);
      const open=IDBFactory.prototype.open;
      IDBFactory.prototype.open=function(database,...args){
        if(database===name&&kind==='open') {hit('open');return {};}
        if(database===name&&kind==='cache') {hit('idb-unavailable');throw new Error('QA optional geometry IDB unavailable');}
        return open.call(this,database,...args);
      };
      const transaction=IDBDatabase.prototype.transaction;
      IDBDatabase.prototype.transaction=function(stores,mode,...args){
        if(this.name===name&&mode==='readwrite'&&kind==='write'){
          hit('write');
          // Browser never delivers request success or transaction completion.
          // Its abort surface remains available to the deadline cleanup.
          const tx={objectStore:()=>({put:()=>({})}),abort(){this.onabort?.();}};
          return tx;
        }
        return transaction.call(this,stores,mode,...args);
      };
      const cacheOpen=CacheStorage.prototype.open;
      CacheStorage.prototype.open=function(cacheName){
        if(cacheName===name&&kind==='cache'){hit('cache');return new Promise(()=>{});}
        return cacheOpen.call(this,cacheName);
      };
    })();""" % json.dumps(kind)


def module_paths():
    """Use the application's actual module identities, including cache versions."""
    source = (SITE / 'assets/js/puzzle-bootstrap.js').read_text('utf-8')
    return {name: 'assets/js/' + re.search(
        rf"from ['\"]\./({re.escape(name)}\.js[^'\"]*)['\"]", source
    ).group(1) for name in ('backend', 'durable-store')}


async def stored(page, base):
    return await page.evaluate("""async ({base,modules,scope})=>{
      const progress=document.querySelector('#geoPuzzleApp').puzzleProgress;
      await progress.capture?.();await progress.flush();
      const {durableStore:store}=await import(base+modules['durable-store']);
      const {backend}=await import(base+modules.backend);
      await store.flush();
      return {draft:await store.loadDraft(scope),
        attempts:await store.listAttempts({owner:scope.owner}),
        pending:await store.listPending({owner:scope.owner,includeDeferred:true}),
        grades:backend.localGrades(),conflicts:await store.listConflicts({owner:scope.owner})};
    }""", {'base': base, 'modules': module_paths(), 'scope': SCOPE})


async def wait_ready(page):
    # Use the shared readiness deadline so a slower CI renderer is not mistaken
    # for a network failure. The loader's actual 12s deadline is not accelerated.
    state = await ready(page)
    assert state['mode'] == 'russia-subjects' and state['total'] == 89, state
    assert len(set(state['featureIds'])) == 89, state['featureIds']
    assert await page.locator('#geoPuzzleApp').get_attribute('data-context') == 'seminar'
    await page.wait_for_function("document.querySelector('#geoPuzzleApp').puzzleProgress.canWrite()")
    await page.locator('#puzzleCanvas').scroll_into_view_if_needed()
    return state


async def seed_legacy_fault(page, base, kind):
    """Preserve actual gameplay; remove geometry persistence before reloading."""
    return await page.evaluate("""async ({base,modules,scope,kind})=>{
      const progress=document.querySelector('#geoPuzzleApp').puzzleProgress;
      await progress.capture?.();await progress.flush();
      // Pagehide must not overwrite the deliberately historical fixture.
      progress.save=()=>Promise.resolve();
      const {durableStore:store}=await import(base+modules['durable-store']);
      const draft=await store.loadDraft(scope),state=structuredClone(draft.state);
      if(kind==='v2-no-ref'){
        state.version=2;delete state.geometryRef;delete state.finishedResult;
        delete state.selections;delete state.view.zoom;
      }
      // Keeping v3 geometryRef while evicting its bytes models device storage
      // eviction. A v2 draft has no ref and must follow its original dataset URL.
      const seeded=await store.checkpoint({...scope,attemptId:draft.attemptId,
        contentVersion:kind==='v2-no-ref'?'puzzle-v2':'puzzle-v3',state},{queue:true});
      await store.flush();
      await new Promise((resolve,reject)=>{
        const open=indexedDB.open('rudn-puzzle-geometry-v1');
        open.onerror=()=>reject(open.error);
        open.onsuccess=()=>{
          const db=open.result;
          if(!db.objectStoreNames.contains('geometry')){db.close();reject(new Error('Missing original geometry store'));return;}
          const tx=db.transaction('geometry','readwrite');tx.objectStore('geometry').clear();
          tx.oncomplete=()=>{db.close();resolve();};tx.onerror=()=>{db.close();reject(tx.error);};
        };
      });
      await caches.delete('rudn-puzzle-geometry-v1');
      return seeded;
    }""", {'base': base, 'modules': module_paths(), 'scope': SCOPE, 'kind': kind})


async def finish_and_verify(page, base, record):
    before = await page.evaluate('window.__puzzleRead()')
    recovered = await stored(page, base)
    geometry_ref = recovered['draft']['state'].get('geometryRef')
    assert geometry_ref, 'Recovered attempt has no saved geometry reference'
    saved_geometry = await page.evaluate("""async ref=>{
      const wrapper=await document.querySelector('#geoPuzzleApp').puzzleProgress.loadGeometry(ref);
      const geometry=wrapper?.geometry;
      const collection=Object.values(geometry?.objects||{})
        .find(item=>item.type==='GeometryCollection'&&item.geometries?.length===89);
      return {available:Boolean(geometry),type:geometry?.type,
        featureIds:collection?.geometries.map(feature=>String(feature.id))};
    }""", geometry_ref)
    assert saved_geometry['available'], 'Recovered geometry reference has no map bytes'
    assert saved_geometry['type'] == 'Topology', saved_geometry
    assert saved_geometry['featureIds'] == before['featureIds'], saved_geometry
    request_counts = (len(record['geometryRequests']), len(record['compactRequests']))
    pointer = 'touch' if record['viewport'][0] <= 768 else 'mouse'
    result = await place_pieces(page, 89, pointer)
    assert result['actual'] == 89 - before['placed'], result
    assert result['state']['finished'] and result['state']['placed'] == 89
    await page.locator('#puzzleResultDialog[open]').wait_for()
    await page.evaluate("""async ({base,backendPath})=>{
      const {backend}=await import(base+backendPath);
      window.__qaMapGradeReady=()=>backend.localGrades()['seminar-2']?.points===4 &&
        backend.localAttempts().some(a=>a.id===window.__puzzleRead().attemptId);
    }""", {'base': base, 'backendPath': module_paths()['backend']})
    # wait_for_function polls the return value synchronously. An async
    # predicate returns a truthy Promise and can finish on its first false
    # result, before the real completion bridge has saved the local grade.
    await page.wait_for_function('window.__qaMapGradeReady()')
    final = await stored(page, base)
    assert len(final['attempts']) == 1, final['attempts']
    attempt = final['attempts'][0]
    assert attempt['id'] == before['attemptId']
    assert attempt['recordGrade'] is True and attempt['gradeEligible'] is True
    assert attempt['activitySlug'] == 'seminar-2' and attempt['draftMode'] == 'seminar'
    assert attempt['points'] == 4 and attempt['maxPoints'] == 5
    assert attempt['placed'] == attempt['total'] == 89
    assert attempt['featureIds'] == before['featureIds']
    assert final['grades']['seminar-2']['points'] == 4
    assert final['draft']['phase'] == 'completed' and final['draft']['state']['finished']
    assert not final['conflicts'], final['conflicts']
    pending = final['pending']
    assert sorted(op['type'] for op in pending) == ['attempt', 'checkpoint'], pending
    assert all(op['attemptId'] == attempt['id'] and op['owner'] == OWNER for op in pending)
    assert next(op['payload'] for op in pending if op['type'] == 'attempt') == attempt
    checkpoint = next(op['payload'] for op in pending if op['type'] == 'checkpoint')
    assert checkpoint['phase'] == 'completed' and checkpoint['state']['placed'] == 89
    await check_layout(page, record, 'completed')

    # Reopening with geometry transport still blocked must not duplicate the
    # immutable attempt, grade or delivery operations.
    await page.reload(wait_until='domcontentloaded')
    await wait_ready(page)
    await page.locator('#puzzleResultDialog[open]').wait_for()
    reopened = await stored(page, base)
    for key in ('attempts', 'grades', 'pending', 'draft'):
        assert reopened[key] == final[key], ('Reload changed durable completion', key)
    assert (len(record['geometryRequests']), len(record['compactRequests'])) == request_counts, (
        'Reload redownloaded geometry instead of using the recovered snapshot',
        record['geometryRequests'], record['compactRequests'])
    record['completion'] = {'attemptId': attempt['id'], 'points': attempt['points'],
                            'placed': attempt['placed'], 'deliveryTypes': ['attempt', 'checkpoint'],
                            'unchangedAfterReload': True, 'geometrySnapshotAvailable': True,
                            'reloadWithoutGeometryRequests': True}


