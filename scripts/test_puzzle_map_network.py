#!/usr/bin/env python3
"""Graded Russia map falls back locally when its original geometry fails.

Run in CI with the existing PuzzleServer's loopback-only identity, unchanged
grading/storage code and read-only engine observation hook. Browser service
workers are blocked so a previous cache cannot conceal a first-visit dependency.
Every completion uses pointer input, never an engine setter/completion shortcut.
The two legacy fixtures are generated by actual play of the original TopoJSON;
only their explicitly documented storage schema/cache faults are then seeded.
"""
from __future__ import annotations

import argparse
import asyncio
from datetime import datetime, timezone
import json
from pathlib import Path
import re
