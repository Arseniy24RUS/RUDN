async def run_case(browser, server, output, case):
    record = {**case, 'browser': browser.browser_type.name, 'status': 'failed',
              'serviceWorkers': 'blocked', 'blockedExternal': [], 'blockedWrites': [],
              'geometryRequests': [], 'compactRequests': [], 'pageErrors': []}
    started = time.monotonic()
    context = await browser.new_context(service_workers='block', reduced_motion='reduce',
                                        viewport=dict(zip(('width', 'height'), case['viewport'])),
                                        has_touch=case['viewport'][0] <= 768)
    await context.add_init_script(initializer('ru'))
    if case.get('storageFault'):
        await context.add_init_script(pending_geometry_storage(case['storageFault']))
    original_phase = bool(case.get('legacy'))
    release = asyncio.Event()

    async def intercept(route):
        request = route.request
        parsed = urlsplit(request.url)
        if request.method not in ('GET', 'HEAD'):
            record['blockedWrites'].append({'url': request.url, 'method': request.method})
            await route.abort('blockedbyclient')
            return
        if not request.url.startswith(server.origin + '/'):
            record['blockedExternal'].append(request.url)
            await route.abort('blockedbyclient')
            return
        if parsed.path == GEOMETRY_PATH:
            record['geometryRequests'].append({'phase': 'legacy-seed' if original_phase else 'test',
                                               'fault': None if original_phase else case['fault']})
            if original_phase or case['fault'] == 'none':
                await route.continue_()
            elif case['fault'] == 'abort':
                await route.abort('failed')
            elif case['fault'] == 'html':
                await route.fulfill(status=200, content_type='text/html',
                                    body='<!doctype html><title>Network sign in</title>')
            else:
                await release.wait()
                try:
                    await route.abort('failed')
                except Exception as error:
                    # Its AbortSignal may have already cancelled this hanging
                    # request; only ignore that specific teardown condition.
                    if not any(text in str(error) for text in (
                        'Target page, context or browser has been closed',
                        'Route is already handled', 'Invalid InterceptionId',
                    )):
                        raise
            return
        if parsed.path == COMPACT_PATH:
            record['compactRequests'].append({'phase': 'legacy-seed' if original_phase else 'test'})
        await route.continue_()

    await context.route('**/*', intercept)
    page = await context.new_page()
    page._qa_base = server.base
    page.on('pageerror', lambda error: record['pageErrors'].append(str(error)))
    page.on('dialog', lambda dialog: asyncio.create_task(dialog.accept()))
    try:
        url = server.base + ('index.html#activity/seminar-2' if case['route'] == 'native'
                             else 'apps/puzzle.html?context=seminar')
        await page.goto(url, wait_until='domcontentloaded')
        if case.get('storageFault'):
            # Reproduce the photographed state before waiting for recovery:
            # the real spinner is visible, all 89 regions are still absent.
            await page.locator('#puzzleLoading').wait_for(state='visible')
            spinner_started = time.monotonic()
            loading = await page.evaluate('window.__puzzleRead()')
            assert loading['loading'] and not loading['ready'] and loading['total'] == 0, loading
            record['pendingSpinnerObserved'] = True
            # A cache deadline must bound startup independently of downloads.
            await page.wait_for_function(
                'window.__puzzleRead().ready && !window.__puzzleRead().loading', timeout=20000)
            record['storageRecoverySeconds'] = round(time.monotonic() - spinner_started, 3)
        initial = await wait_ready(page)
        assert initial['difficulty'] == 'medium' and initial['placed'] == 0
        assert initial['ready'] and not initial['loading'] and initial['elapsedMs'] == 0
        record['readySeconds'] = round(time.monotonic() - started, 3)
        await check_layout(page, record, 'ready')
        await trusted_drop(page)
        if case.get('legacy'):
            await trusted_drop(page)
            await page.locator('#puzzleHint').click()
            await page.locator('#puzzleReturn').click()
            seeded = await seed_legacy_fault(page, server.base, case['legacy'])
            assert len(record['geometryRequests']) == 1, record['geometryRequests']
            original_phase = False
            await page.reload(wait_until='domcontentloaded')
            restored = await wait_ready(page)
            for key in ('attemptId', 'order', 'featureIds', 'placed', 'hints', 'difficulty', 'current'):
                assert restored[key] == seeded['state'][key], ('Legacy restore changed state', key)
            assert restored['placed'] == 2 and restored['hints'] == 1
            assert restored['elapsedMs'] >= seeded['state']['elapsedMs']
            record['legacyRestore'] = {'schema': case['legacy'], 'placed': 2,
                                       'sameAttemptOrderAndIds': True, 'originalGeometryPlayed': True}
        if case.get('storageFault'):
            hits = await page.evaluate('window.__qaGeometryFaultHits')
            assert case['storageFault'] in hits, ('Fault was never reached', hits)
            saved = await stored(page, server.base)
            assert saved['draft']['state']['placed'] == 1, saved['draft']
            assert saved['draft']['state']['featureIds'] == initial['featureIds']
            assert not saved['attempts'] and 'seminar-2' not in saved['grades'], saved
            geometry_ref = saved['draft']['state'].get('geometryRef')
            assert geometry_ref, 'The running attempt lost its map reference'
            # A slow disk must not invalidate geometry already held in memory.
            available = await page.evaluate("""async ref=>Boolean(
                (await document.querySelector('#geoPuzzleApp').puzzleProgress.loadGeometry(ref))?.geometry
            )""", geometry_ref)
            assert available, 'In-memory geometry disappeared after optional-cache timeout'
            record['storageRecovery'] = {'faultStages': hits, 'renderedRegions': initial['total'],
                                         'trustedPointerPlaced': 1, 'progressSaved': True,
                                         'inMemoryGeometryAvailable': True}
        else:
            await finish_and_verify(page, server.base, record)
        primary_test = [r for r in record['geometryRequests'] if r['phase'] == 'test']
        compact_test = [r for r in record['compactRequests'] if r['phase'] == 'test']
        assert primary_test, 'Primary geometry path was bypassed'
        if case['fault'] == 'none':
            assert not compact_test, 'Compact map fetched despite healthy original'
        else:
            assert compact_test, 'Original failure did not load the same-origin compact map'
        assert not [r for r in record['compactRequests'] if r['phase'] == 'legacy-seed']
        record['primaryRemainsDefault'] = True
        assert not record['pageErrors'], record['pageErrors']
        assert not record['blockedWrites'], record['blockedWrites']
        record['status'] = 'passed'
        await page.screenshot(path=str(output / (case['name'] + '.png')))
    except Exception as error:
        record['error'] = str(error)
        record['traceback'] = traceback.format_exc()
        try:
            record['lastState'] = await page.evaluate('window.__puzzleRead?.()')
            await page.screenshot(path=str(output / (case['name'] + '-failure.png')), timeout=5000)
        except Exception:
            pass
    finally:
        release.set()
        await context.close()
        record['seconds'] = round(time.monotonic() - started, 3)
    return record


async def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--browsers', default='chromium')
    parser.add_argument('--only', choices=[case['name'] for case in CASES])
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True)
    results = []
    with PuzzleServer(args.output) as server:
        async with async_playwright() as playwright:
            for browser_name in args.browsers.split(','):
                browser_output = args.output / browser_name
                browser_output.mkdir(exist_ok=True)
                browser = await getattr(playwright, browser_name).launch(
                    **({'firefox_user_prefs': {'network.proxy.type': 0}} if browser_name == 'firefox' else {}))
                browser_results = []
                try:
                    for case in CASES:
                        if args.only and case['name'] != args.only:
                            continue
                        record = await run_case(browser, server, browser_output, case)
                        browser_results.append(record)
                        print(json.dumps({'browser': browser_name, 'case': case['name'],
                                          'status': record['status'], 'error': record.get('error')}, ensure_ascii=False), flush=True)
                finally:
                    await browser.close()
                    results.extend(browser_results)
                    (browser_output / 'map-network.json').write_text(json.dumps({
                        'createdAt': datetime.now(timezone.utc).isoformat(),
                        'browser': browser_name, 'cases': browser_results,
                    }, ensure_ascii=False, indent=2), encoding='utf-8')
    if not results or any(record['status'] != 'passed' for record in results):
        raise SystemExit(1)


if __name__ == '__main__':
    asyncio.run(main())
