import {build} from 'esbuild';
import {readFile, writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';

const root = new URL('../', import.meta.url);
const vendor = new URL('node_modules/fflate/', root);
const {version} = JSON.parse(await readFile(new URL('package.json', vendor), 'utf8'));
const license = (await readFile(new URL('LICENSE', vendor), 'utf8')).trim();
const {outputFiles} = await build({
  stdin: {contents: "export {gunzipSync} from 'fflate';", resolveDir: fileURLToPath(root)},
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2020',
  minify: true,
  write: false,
  banner: {js: `/* Generated by scripts/build-settlements-gzip.mjs from fflate ${version}.\n\n${license}\n*/`},
});
const target = new URL('site/apps/settlements/runtime/assets/js/settlements/v2/gzip-fallback.mjs', root);
const bytes = Buffer.from(outputFiles[0].contents);
if (process.argv.includes('--check')) {
  if (!bytes.equals(await readFile(target))) throw new Error('Settlements gzip fallback is stale');
} else {
  await writeFile(target, bytes);
}
console.log(`Settlements gzip fallback from fflate ${version}: ${bytes.length} bytes`);
