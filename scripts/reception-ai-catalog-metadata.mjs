#!/usr/bin/env node
/** Public assignment metadata only. Never imports case bodies or answer keys. */
import {readFile, writeFile} from 'node:fs/promises';
import {CONTENT_MANIFEST} from '../site/apps/reception/content/manifest.js';

const target = new URL('../firebase/functions/reception-ai/catalog-metadata.mjs', import.meta.url);
const rows = Object.fromEntries(CONTENT_MANIFEST.templates.map(({id, familyId, level, estimatedMinutes}) => {
  if (!id || !familyId || ![1, 2, 3].includes(level) || !Number.isFinite(estimatedMinutes) || estimatedMinutes <= 0) {
    throw new TypeError('Invalid public assignment metadata');
  }
  return [id, {familyId, level, estimatedMinutes}];
}));
const calendarTerms = Object.fromEntries(CONTENT_MANIFEST.templates.map(({id, calendar}) => {
  if (!['calendarDays', 'workingDays', 'calendarMonths'].includes(calendar?.unit)
    || !Number.isInteger(calendar.duration) || calendar.duration <= 0) throw new TypeError('Invalid assignment calendar metadata');
  return [id, calendar.unit === 'workingDays' ? 'workingDays' : `${calendar.unit}:${calendar.duration}`];
}));
const source = '// Generated by scripts/reception-ai-catalog-metadata.mjs from the public content manifest.\n'
  + '// Contains assignment metadata only: no event dates, private facts, scoring rubrics, or case bodies.\n'
  + `export const CATALOG_METADATA_VERSION = ${JSON.stringify(CONTENT_MANIFEST.contentVersion)};\n`
  + `export const CATALOG_METADATA = Object.freeze(${JSON.stringify(rows, null, 2)});\n`
  + '// Server-side assignment coverage. Never included in catalog responses or actor context.\n'
  + `export const CATALOG_CALENDAR_TERMS = Object.freeze(${JSON.stringify(calendarTerms, null, 2)});\n`;
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== source) throw new Error('Catalog metadata is stale; run node scripts/reception-ai-catalog-metadata.mjs');
} else await writeFile(target, source);
console.log(`Public reception metadata: ${Object.keys(rows).length} cases (${process.argv.includes('--check') ? 'verified' : 'written'}).`);
